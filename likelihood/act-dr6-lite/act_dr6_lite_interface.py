try:
    import act_dr6_cmbonly
except ImportError:
    raise RuntimeError('The act_dr6_cmbonly python module is required for the act_dr6_lite likelihood. It can be obtained from https://github.com/ACTCollaboration/DR6-ACT-lite')
from cosmosis.datablock import option_section, names
cosmo = names.cosmological_parameters
import numpy as np
import os


cal_params = [
    "A_act",
    "P_act"
]

dirname = os.path.split(__file__)[0]


def setup(options):
    act = act_dr6_cmbonly.ACTDR6CMBonly(packages_path=dirname)

    # Optionally restrict the range of ell used for each spectrum.
    # The defaults reproduce the standard ACT DR6 lite analysis
    for pol in ['tt', 'te', 'ee']:
        ell_min = options.get_int(option_section, f'ell_min_{pol}', default=600)
        ell_max = options.get_int(option_section, f'ell_max_{pol}', default=6500)
        act.ell_cuts[pol.upper()] = [ell_min, ell_max]

    # Theory spectra are needed up to this ell
    act.lmax_theory = 8500

    # Reset the internal prior setting and re-initialize so that the
    # changed ell ranges are applied to the data
    act.params = {}
    act.initialize()
    for pol, (lmin, lmax) in act.ell_cuts.items():
        print(f"ACT: using {pol} data in the range [{lmin}-{lmax}]")

    # Optionally replace the real data with synthetic data, generated by
    # running the test sampler with save_dir set to this directory.
    sim_data_directory = options.get_string(option_section, 'use_data_from_test', default='')
    if sim_data_directory != '':
        print('ACT likelihood uses synthetic data from:', sim_data_directory)
        sim_cl_dict = {}
        for pol in ['tt', 'te', 'ee']:
            cl = np.genfromtxt(os.path.join(sim_data_directory, 'cmb_cl', f'{pol}.txt'))
            # prepend zeros for ell = 0, 1
            sim_cl_dict[pol] = np.append(np.zeros(2), cl)

        ps_vec = np.zeros_like(act.data_vec)
        for m in act.spec_meta:
            win = m["window"].weight.T
            ls = m["window"].values
            ps_vec[m["idx"]] = win @ sim_cl_dict[m["pol"]][ls]
        act.data_vec = ps_vec

    return act


def execute(block, config):
    act = config
    cl_dict = {
        "tt": np.append(np.array([0,0]), block[names.cmb_cl, 'tt']),
        "te": np.append(np.array([0,0]), block[names.cmb_cl, 'te']),
        "ee": np.append(np.array([0,0]), block[names.cmb_cl, 'ee']),
    }

    if block.has_value("planck", "a_planck"):
        # When ACT is combined with Planck, they share calibration parameters
        # https://github.com/ACTCollaboration/DR6-ACT-lite/issues/12
        # when a_planck is found in value.ini, A_act is fixed to a_planck
        block["act_params", "A_act"] = block["planck", "a_planck"]

    nuisance = {}

    for p in cal_params:
        nuisance[p] = block["act_params", p]

    loglike = act.loglike(cl_dict, **nuisance)
    # Then call the act code
    block[names.likelihoods, 'act_dr6_lite_like'] = loglike

    return 0
